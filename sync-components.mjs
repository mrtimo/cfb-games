// =====================================================================
//  Build the games report components.
//
//  A malloyyo component may import only React and @malloyyo/dashboard,
//  so the 2025 and 2026 games reports cannot share a module. Instead
//  both are generated from the same two parts:
//
//    components/drive-chart.part.tsx    the React/SVG drive chart
//    components/games-report.part.tsx   the page
//
//  and are byte-identical — everything season-specific lives in each
//  dashboard's .malloy file. Edit the parts, then:
//
//    node sync-components.mjs
// =====================================================================

import { readFileSync, writeFileSync } from "node:fs";

const here = new URL(".", import.meta.url);
const read = (p) => readFileSync(new URL(p, here), "utf8");

const SEASONS = ["2025", "2026"];

const banner = `// =====================================================================
//  GENERATED by sync-components.mjs from components/*.part.tsx.
//  Do not edit here: edit the parts and re-run \`node sync-components.mjs\`.
// =====================================================================
`;

const imports = `import React, { useEffect, useMemo, useState } from "react";
import { Controls, Given, useGiven, useQuery, useUrlState, filters } from "@malloyyo/dashboard";
`;

const body = [banner, imports, read("components/drive-chart.part.tsx"), read("components/games-report.part.tsx")].join("\n");

for (const season of SEASONS) {
  const out = `dashboards/games-${season}.tsx`;
  writeFileSync(new URL(out, here), body);
  console.log(`  wrote ${out}`);
}
